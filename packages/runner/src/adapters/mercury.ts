import type { Witness } from "@nevergraph/schemas";
import type { WitnessTestAdapter } from "../types.js";

export interface MercuryWitnessTestAdapterOptions {
  /** Module imported by the generated isolated integration test. */
  moduleSpecifier: string;
}

const ACTION_FUNCTIONS: Readonly<Record<string, string>> = Object.freeze({
  payOrder: "payOrder",
  refundOrder: "refundOrder",
  cancelOrder: "cancelOrder",
  restoreOrder: "restoreOrder",
  shipOrder: "shipOrder",
});

/** Mercury-specific template adapter; generic runner modules do not import it. */
export function createMercuryWitnessTestAdapter(
  options: MercuryWitnessTestAdapterOptions,
): WitnessTestAdapter {
  if (options.moduleSpecifier.trim().length === 0) {
    throw new Error("moduleSpecifier must be non-empty");
  }

  return {
    id: "mercury-order-lifecycle",
    safetyAssertion: "path_must_throw",
    supports(witness: Witness): boolean {
      return witness.steps.length > 0 && witness.steps.every(
        (step) => Object.prototype.hasOwnProperty.call(ACTION_FUNCTIONS, step.action),
      );
    },
    generateTest({ identifier, witness }): string {
      const actionFunctions = orderedUnique(
        witness.steps.map((step) => ACTION_FUNCTIONS[step.action]!),
      );
      const imports = ["createOrder", ...actionFunctions].join(", ");
      const calls = actionFunctionsForWitness(witness)
        .map((action) => `      ${action}(order);`)
        .join("\n");

      return [
        "// AUTO-GENERATED by NeverGraph — DO NOT EDIT",
        `// Witness: ${identifier} (${witness.length} transitions)`,
        'import { describe, expect, it } from "vitest";',
        `import { ${imports} } from ${JSON.stringify(options.moduleSpecifier)};`,
        "",
        `describe(${JSON.stringify(`${identifier} negative specification`)}, () => {`,
        '  it("keeps the forbidden outcome unreachable", () => {',
        "    const order = createOrder();",
        "",
        "    expect(() => {",
        calls,
        "    }).toThrow();",
        "  });",
        "});",
      ].join("\n");
    },
  };
}

function actionFunctionsForWitness(witness: Witness): string[] {
  return witness.steps.map((step) => ACTION_FUNCTIONS[step.action]!);
}

function orderedUnique(values: string[]): string[] {
  return [...new Set(values)];
}
